-- ======================================================================
-- VOCALYZE DATABASE SCHEMA (MySQL 8.0+)
-- Database : dbms_project
-- Charset  : utf8mb4  (English, हिंदी, ಕನ್ನಡ)
-- Auth     : Pure MySQL + JWT (no Firebase)
-- ======================================================================

CREATE DATABASE IF NOT EXISTS dbms_project
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE dbms_project;

-- ======================================================================
-- TABLE 1: users
--   Stores credentials, profile, and accessibility preferences.
--   password_hash + password_salt → PBKDF2-SHA512 (Node.js crypto)
--   preferred_language, accessibility_needs, interaction_preferences
--     are stored inline to keep the data model simple.
-- ======================================================================
CREATE TABLE IF NOT EXISTS users (
    id                      BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    uid                     VARCHAR(64)  NOT NULL UNIQUE
                            COMMENT 'UUID v4 generated by the application',
    name                    VARCHAR(150) NOT NULL,
    email                   VARCHAR(255) NOT NULL UNIQUE,
    password_hash           VARCHAR(255) NULL
                            COMMENT 'PBKDF2-SHA512 hex string',
    password_salt           VARCHAR(64)  NULL
                            COMMENT 'Cryptographic salt (32 hex chars)',
    role                    ENUM('citizen','officer','admin') DEFAULT 'citizen',
    is_active               BOOLEAN      DEFAULT TRUE,

    -- Accessibility profile (inline JSON — avoids extra JOIN on every request)
    preferred_language      ENUM('en','hi','kn') DEFAULT 'en',
    accessibility_needs     JSON         NULL
                            COMMENT 'Array of need codes, e.g. ["visual","hearing"]',
    interaction_preferences JSON         NULL
                            COMMENT '{"voiceInput":true,"voiceOutput":true,...}',

    created_at              TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP    DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

    INDEX idx_users_email (email),
    INDEX idx_users_uid   (uid)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


-- ======================================================================
-- TABLE 2: services
--   Government service definitions.
--   Multilingual name/description stored as separate columns (en/hi/kn).
--   Form questions stored as a JSON array for flexibility.
-- ======================================================================
CREATE TABLE IF NOT EXISTS services (
    id               INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    service_id       VARCHAR(64)  NOT NULL UNIQUE
                     COMMENT 'Slug: pension-certificate, disability-certificate, income-certificate',
    name_en          VARCHAR(255) NOT NULL,
    name_hi          VARCHAR(255) NOT NULL,
    name_kn          VARCHAR(255) NOT NULL,
    description_en   TEXT         NOT NULL,
    description_hi   TEXT         NOT NULL,
    description_kn   TEXT         NOT NULL,
    category         VARCHAR(64)  NOT NULL
                     COMMENT 'social welfare | healthcare | revenue',
    enabled          BOOLEAN      DEFAULT TRUE,
    questions        JSON         NOT NULL
                     COMMENT 'Array of question objects with id, type, required, label{en,hi,kn}',
    created_at       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

    INDEX idx_services_category (category),
    INDEX idx_services_enabled  (enabled)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


-- ======================================================================
-- TABLE 3: applications
--   Tracks each citizen's government service application.
--   answers stored as JSON map  { fieldKey: "value", ... }.
--   user_uid is a VARCHAR FK matching users.uid (not users.id).
-- ======================================================================
CREATE TABLE IF NOT EXISTS applications (
    id               BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    application_id   VARCHAR(20)  NOT NULL UNIQUE
                     COMMENT 'Human-readable ID, e.g. APP-2026-82341',
    service_id       VARCHAR(64)  NOT NULL
                     COMMENT 'References services.service_id',
    user_uid         VARCHAR(64)  NOT NULL
                     COMMENT 'References users.uid',
    status           ENUM('IN_PROGRESS','SUBMITTED','APPROVED','REJECTED')
                     NOT NULL DEFAULT 'IN_PROGRESS',
    answers          JSON         NOT NULL DEFAULT (JSON_OBJECT())
                     COMMENT 'Form answers map, e.g. {"fullName":"Ravi","phone":"9876543210"}',
    created_at       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

    INDEX idx_app_user_uid   (user_uid),
    INDEX idx_app_service    (service_id),
    INDEX idx_app_status     (status),

    CONSTRAINT fk_app_user FOREIGN KEY (user_uid)
        REFERENCES users (uid) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


